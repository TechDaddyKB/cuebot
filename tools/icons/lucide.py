"""Converts Lucide icons (lucide-static SVGs) into Avalonia StreamGeometry resources for src/Cuebot.App/Styles/Icons.axaml.

Usage: npm pack lucide-static@<version> && tar -xzf lucide-static-<version>.tgz
       python3 tools/icons/lucide.py <path to package/icons> <version>
Add an icon by putting its Lucide name in ICONS and running the script again. Icons draw as 2-unit strokes on a 24x24
grid (see Controls/Icon.cs); every element becomes path data.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ICONS = """
house zap message-square audio-lines layout-grid radio layers plug settings search plus ellipsis play save
chevron-down chevron-right x check trash-2 pencil copy external-link refresh-cw circle-alert triangle-alert info
user users folder clock mic volume-2 gamepad-2 keyboard link panel-left-close panel-left-open square-terminal
sparkles gift heart star bot list-checks timer variable cable monitor
""".split()

OUT = Path(__file__).resolve().parents[2] / "src/Cuebot.App/Styles/Icons.axaml"


def num(v):
    return float(v or 0)


def fmt(x):
    return ("%.3f" % x).rstrip("0").rstrip(".")


def element_to_path(el):
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        # Each SVG path starts fresh, so a leading relative move is absolute; joined into one geometry it would not be.
        # Further coordinate pairs after that move stay relative line-tos.
        d = a["d"].strip()
        m = re.match(r"m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)", d)
        if not m:
            return d
        rest = d[m.end():].lstrip(" ,")
        return f"M{m.group(1)} {m.group(2)}" + (" l" + rest if rest and not rest[0].isalpha() else " " + rest)
    if tag == "circle":
        cx, cy, r = num(a.get("cx")), num(a.get("cy")), num(a.get("r"))
        return f"M{fmt(cx - r)} {fmt(cy)}a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2 * r)} 0a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2 * r)} 0Z"
    if tag == "ellipse":
        cx, cy, rx, ry = (num(a.get(k)) for k in ("cx", "cy", "rx", "ry"))
        return f"M{fmt(cx - rx)} {fmt(cy)}a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2 * rx)} 0a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2 * rx)} 0Z"
    if tag == "rect":
        x, y, w, h = (num(a.get(k)) for k in ("x", "y", "width", "height"))
        rx = num(a.get("rx", a.get("ry")))
        ry = num(a.get("ry", a.get("rx")))
        if rx == 0:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        return (f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(ry)}"
                f"v{fmt(h - 2 * ry)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(ry)}h{fmt(-(w - 2 * rx))}"
                f"a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(-ry)}v{fmt(-(h - 2 * ry))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(-ry)}Z")
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{pts[i]} {pts[i + 1]}" for i in range(0, len(pts) - 1, 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    raise ValueError(f"unsupported element <{tag}>")


def main():
    icons_dir, version = Path(sys.argv[1]), sys.argv[2]
    lines = []
    for name in sorted(ICONS):
        root = ET.parse(icons_dir / f"{name}.svg").getroot()
        data = " ".join(element_to_path(el) for el in root)
        lines.append(f'  <StreamGeometry x:Key="Icon.{name}">{data}</StreamGeometry>')
    OUT.write_text(f"""<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <!--
    Lucide icons {version} (https://lucide.dev, ISC licence; icons derived from Feather under MIT), generated by
    tools/icons/lucide.py: do not edit by hand. Each is drawn on a 24x24 grid with a 2-unit stroke by Controls/Icon.
  -->
{chr(10).join(lines)}
</ResourceDictionary>
""", encoding="utf-8")
    print(f"wrote {len(lines)} icons to {OUT}")


if __name__ == "__main__":
    main()
