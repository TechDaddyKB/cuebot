    private static readonly Lazy<FrozenDictionary<string, int[]>> ByTrigger = new(BuildByTrigger);

    /// <summary>The Streamer.bot trigger with <paramref name="code"/>, or null when Streamer.bot 1.0.7 has none.</summary>
    public static StreamerBotTrigger? Get(int code)
    {
        if (!Paths.TryGetValue(code, out var path)) return null;
        var segments = path.Split(" > ");
        return new StreamerBotTrigger(code, string.Join('/', segments[..^1]), segments[^1], EventSourceOf(segments));
    }

    /// <summary>
    /// The Streamer.bot trigger a Cuebot trigger stands for, or null when Streamer.bot has no equivalent. Triggers that
    /// several Streamer.bot triggers import to (first words, present viewers, 7TV/BTTV emotes) are told apart by the
    /// event's <c>platform</c> and <c>provider</c>, else the trigger's settings of those names.
    /// </summary>
    public static StreamerBotTrigger? For(string triggerTypeId, IReadOnlyDictionary<string, object?> args,
        IReadOnlyDictionary<string, string>? settings = null)
    {
        var platform = Text(args, settings, "platform").ToLowerInvariant();
        int? code = triggerTypeId switch
        {
            "users.firstWords" => platform switch { "twitch" => 120, "youtube" => 4016, "kick" => 35008, _ => null },
            "users.presentViewers" => platform switch { "twitch" => 124, "youtube" => 4017, "kick" => 35009, _ => null },
            "chat.emoteAdded" or "chat.emoteRemoved" => Emote(triggerTypeId == "chat.emoteAdded", platform, Text(args, settings, "provider")),
            "custom.codeEvent" => 18001,
            _ => ByTrigger.Value.TryGetValue(triggerTypeId, out var codes) && codes.Length == 1 ? codes[0] : null,
        };
        return code is { } c ? Get(c) : null;
    }

    private static int? Emote(bool added, string platform, string provider) => (platform, provider.ToUpperInvariant()) switch
    {
        ("twitch" or "", "7TV") => added ? 180 : 181,
        ("twitch" or "", "BTTV") => added ? 182 : 183,
        ("kick", "7TV") => added ? 35021 : 35022,
        _ => null,
    };

    /// <summary>Cuebot trigger type → the codes whose import rule targets it (codes Streamer.bot 1.0.7 knows only).</summary>
    private static FrozenDictionary<string, int[]> BuildByTrigger() => StreamerBotMappingTable.Default.Triggers
        .SelectMany(r => r.TypeKeys.Select(k => (r.TargetType, Code: int.TryParse(k, NumberStyles.None, CultureInfo.InvariantCulture, out var n) ? n : -1)))
        .Where(x => Paths.ContainsKey(x.Code))
        .GroupBy(x => x.TargetType, StringComparer.Ordinal)
        .ToFrozenDictionary(g => g.Key, g => g.Select(x => x.Code).Distinct().ToArray(), StringComparer.Ordinal);

    /// <summary>Streamer.bot's event source for a trigger path: the lowercase <c>EventSource</c> name of its runs.</summary>
    private static string EventSourceOf(string[] path) => path[0] switch
    {
        "Core" => path.Length > 2 ? path[1] switch
        {
            "File IO" => "filetail",
            "File/Folder Watcher" => "filewatcher",
            "Groups" => "group",
            "Inputs" => "inputs",
            "MIDI" => "midi",
            "Commands" => "command",
            "Quotes" => "quote",
            "Voice Control" => "speechtotext",
            "Websocket" => path[2] == "Client" ? "websocketclient" : "websocketcustomserver",
            _ => "misc", // Global Variables, Processes, System (Toast Activation reports "misc")
        } : "misc",
        "Elgato" => path[1] == "Stream Deck" ? "streamdeck" : "elgato",
        "Integrations" => path[1] == "HypeRate.io" ? "hyperate" : Lower(path[1]),
        _ => Lower(path[0]), // Twitch, YouTube, Kick, OBS Studio → obs, Streamlabs Desktop, Meld Studio, Custom
    };

    private static string Lower(string name) => name switch
    {
        "OBS Studio" => "obs",
        _ => new string(name.Where(char.IsLetterOrDigit).Select(char.ToLowerInvariant).ToArray()),
    };

    private static string Text(IReadOnlyDictionary<string, object?> args, IReadOnlyDictionary<string, string>? settings, string name) =>
        args.TryGetValue(name, out var v) && v is not null && Convert.ToString(v, CultureInfo.InvariantCulture) is { Length: > 0 } text
            ? text
            : settings?.GetValueOrDefault(name) ?? "";
