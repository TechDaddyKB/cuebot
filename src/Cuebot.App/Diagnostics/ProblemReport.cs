using System.Text;
using System.Text.Json;
using Cuebot.Core;
using Cuebot.Core.Storage;

namespace Cuebot.App.Diagnostics;

/// <summary>What the user typed into the report form.</summary>
public sealed record ReportInput
{
    public string Title { get; init; } = "";
    public string Summary { get; init; } = "";
    public string Steps { get; init; } = "";
    public string Expected { get; init; } = "";
    public string Actual { get; init; } = "";
}

/// <summary>Which auto-collected sections go into the report.</summary>
public sealed record ReportOptions
{
    public bool IncludeConnections { get; init; } = true;
    public bool IncludeAppSettings { get; init; } = true;
    public bool IncludeModuleSettings { get; init; }
    public bool IncludeLog { get; init; } = true;
    public bool IncludeCrash { get; init; } = true;
    public bool IncludeAccountNames { get; init; }
    public string? HomeFolder { get; init; } = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
}

/// <summary>Raw facts gathered from this machine (not yet scrubbed); see <see cref="InfoGatherer"/>.</summary>
public sealed record CollectedInfo
{
    public EnvironmentSnapshot Environment { get; init; } = new();
    public IReadOnlyList<ConnectionInfo> Connections { get; init; } = [];

    /// <summary>app.json text, or null when there is none.</summary>
    public string? AppSettings { get; init; }

    /// <summary>Module settings files by file name (twitch.json, ...).</summary>
    public IReadOnlyDictionary<string, string> ModuleSettings { get; init; } = new Dictionary<string, string>();

    public IReadOnlyList<string> Log { get; init; } = [];
    public CrashRecord? Crash { get; init; }
    public string? CrashFile { get; init; }

    /// <summary>Account names found in the settings files, removed from text unless the user opts in.</summary>
    public IReadOnlyCollection<string> AccountNames { get; init; } = [];
}

/// <summary>Reads what a report can include from the data folder; never reads secrets into the report unscrubbed.</summary>
public static class InfoGatherer
{
    /// <summary>Settings files worth attaching (configuration, not user data such as users, quotes or points).</summary>
    public static readonly string[] ModuleSettingsFiles =
    [
        "twitch.json", "youtube.json", "kick.json", "rumble.json", "obs.json", "donations.json", "speech.json",
        "servers.json", "scripting.json", "desktop.json", "hotkeys.json", "streamlabs-desktop.json", "obswebsocket.json",
    ];

    private const int MaxSettingsFileBytes = 256 * 1024;

    public static CollectedInfo Gather(AppPaths paths, EnvironmentSnapshot environment, IReadOnlyList<ConnectionInfo> connections,
        string? crashFile = null)
    {
        var modules = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var name in ModuleSettingsFiles)
            if (ReadSmall(paths.File(name)) is { } text) modules[name] = text;
        var accounts = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var text in modules.Values) accounts.UnionWith(SecretScrubber.CollectAccountNames(text));
        return new CollectedInfo
        {
            Environment = environment,
            Connections = connections,
            AppSettings = ReadSmall(paths.File("app.json")),
            ModuleSettings = modules,
            Log = LogTail.Read(paths.Logs),
            Crash = crashFile is null ? null : CrashStore.Read(crashFile),
            CrashFile = crashFile,
            AccountNames = accounts,
        };
    }

    private static string? ReadSmall(string path)
    {
        try
        {
            var file = new FileInfo(path);
            return file.Exists && file.Length <= MaxSettingsFileBytes ? File.ReadAllText(path) : null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { return null; }
    }
}

/// <summary>
/// Builds the Markdown issue body: the user's text, an environment table, then collapsible auto-collected sections.
/// Every collected value passes through <see cref="SecretScrubber"/>.
/// </summary>
public static class ReportBuilder
{
    public const string Footer = "_Generated by Cuebot's problem reporter. Secrets were removed automatically; please check the text before posting._";

    public const string PasteMarker =
        "> **The full report (logs, settings, crash details) was copied to your clipboard. Select this line and paste to replace it.**";

    public static ScrubOptions ScrubOptionsFor(ReportOptions options, CollectedInfo info) => new()
    {
        IncludeAccountNames = options.IncludeAccountNames,
        KnownAccountNames = info.AccountNames,
        HomeFolder = options.HomeFolder,
    };

    public static string DefaultTitle(CollectedInfo info) =>
        info.Crash is { } crash ? Truncate($"Crash: {SecretScrubber.ScrubText(crash.Summary)}", 120) : "";

    public static string Build(ReportInput input, CollectedInfo info, ReportOptions options)
    {
        var scrub = ScrubOptionsFor(options, info);
        var sb = new StringBuilder();
        AppendUserSections(sb, input, scrub);
        AppendEnvironment(sb, info.Environment);

        if (options.IncludeCrash && info.Crash is { } crash)
        {
            sb.Append("### Crash\n\n");
            sb.Append($"Cuebot closed unexpectedly at {crash.Time:yyyy-MM-dd HH:mm:ss zzz} ({crash.Source}).\n\n");
            sb.Append(Fence(SecretScrubber.ScrubText(crash.Exception.Format(), scrub), "text"));
            sb.Append('\n');
            var json = SecretScrubber.ScrubJson(JsonSerializer.Serialize(crash, Json.Options), scrub);
            AppendDetails(sb, "Crash file (secrets removed)", Fence(json, "json"));
        }
        if (options.IncludeConnections && info.Connections.Count > 0)
        {
            var lines = info.Connections.Select(c =>
            {
                var message = options.IncludeAccountNames && c.Message.Length > 0 ? $" — {SecretScrubber.ScrubText(c.Message, scrub)}" : "";
                return $"- {c.Name}: {c.State}{message}";
            });
            AppendDetails(sb, "Connections", string.Join('\n', lines) + "\n");
        }
        if (options.IncludeAppSettings && !string.IsNullOrWhiteSpace(info.AppSettings))
            AppendDetails(sb, "App settings (app.json, secrets removed)", Fence(SecretScrubber.ScrubJson(info.AppSettings, scrub), "json"));
        if (options.IncludeModuleSettings)
            foreach (var (name, text) in info.ModuleSettings.OrderBy(m => m.Key, StringComparer.Ordinal))
                AppendDetails(sb, $"{name} (secrets removed)", Fence(SecretScrubber.ScrubJson(text, scrub), "json"));
        if (options.IncludeLog && info.Log.Count > 0)
            AppendDetails(sb, $"Recent log (last {info.Log.Count} lines, secrets removed)",
                Fence(string.Join('\n', info.Log.Select(l => SecretScrubber.ScrubText(l, scrub))), "text"));

        sb.Append(Footer).Append('\n');
        return sb.ToString();
    }

    /// <summary>The body used in the URL when the full report is too long: user text, environment, paste marker.</summary>
    public static string BuildShort(ReportInput input, CollectedInfo info, ReportOptions options)
    {
        var scrub = ScrubOptionsFor(options, info);
        var sb = new StringBuilder();
        AppendUserSections(sb, input, scrub);
        AppendEnvironment(sb, info.Environment);
        if (options.IncludeCrash && info.Crash is { } crash)
            sb.Append($"### Crash\n\n`{SecretScrubber.ScrubText(crash.Summary, scrub).Replace('`', '\'')}`\n\n");
        sb.Append(PasteMarker).Append("\n\n");
        sb.Append(Footer).Append('\n');
        return sb.ToString();
    }

    private static void AppendUserSections(StringBuilder sb, ReportInput input, ScrubOptions scrub)
    {
        Section(sb, "Summary", input.Summary, scrub);
        Section(sb, "Steps to reproduce", input.Steps, scrub);
        Section(sb, "Expected behaviour", input.Expected, scrub);
        Section(sb, "Actual behaviour", input.Actual, scrub);
    }

    private static void Section(StringBuilder sb, string heading, string text, ScrubOptions scrub)
    {
        sb.Append("### ").Append(heading).Append("\n\n");
        sb.Append(string.IsNullOrWhiteSpace(text) ? "_No response_" : SecretScrubber.ScrubText(text.Trim(), scrub)).Append("\n\n");
    }

    private static void AppendEnvironment(StringBuilder sb, EnvironmentSnapshot env)
    {
        sb.Append("### Environment\n\n| | |\n| --- | --- |\n");
        foreach (var (label, value) in env.Rows())
            sb.Append("| ").Append(label).Append(" | ").Append(value.Replace("|", "\\|").Replace('\n', ' ')).Append(" |\n");
        sb.Append('\n');
    }

    private static void AppendDetails(StringBuilder sb, string summary, string body)
    {
        sb.Append("<details><summary>").Append(summary).Append("</summary>\n\n").Append(body).Append("\n</details>\n\n");
    }

    /// <summary>A code block whose fence is longer than any backtick run inside the content.</summary>
    public static string Fence(string content, string language)
    {
        var longest = 0;
        var run = 0;
        foreach (var c in content)
        {
            run = c == '`' ? run + 1 : 0;
            longest = Math.Max(longest, run);
        }
        var fence = new string('`', Math.Max(3, longest + 1));
        return $"{fence}{language}\n{content.TrimEnd()}\n{fence}\n";
    }

    public static string Truncate(string s, int max) => s.Length <= max ? s : s[..(max - 1)] + "…";
}

/// <summary>The "new issue" link GitHub opens prefilled. GitHub rejects very long URLs, so long bodies are cut short.</summary>
public sealed record IssueLink(string Url, bool BodyTruncated)
{
    /// <summary>A conservative limit below what GitHub and browsers accept (about 8 KB).</summary>
    public const int MaxUrlLength = 7500;

    public const int MaxTitleLength = 200;

    public static string BuildUrl(string title, string body) =>
        $"{SupportLinks.NewIssueUrl}?title={Uri.EscapeDataString(title)}&labels=bug&body={Uri.EscapeDataString(body)}";

    /// <summary>
    /// The full body when it fits; otherwise <paramref name="shortBody"/> (cut further if needed), and the caller copies
    /// the full report to the clipboard.
    /// </summary>
    public static IssueLink Create(string title, string fullBody, string shortBody, int maxLength = MaxUrlLength)
    {
        title = ReportBuilder.Truncate(string.IsNullOrWhiteSpace(title) ? "Problem report" : title.Trim(), MaxTitleLength);
        var full = BuildUrl(title, fullBody);
        if (full.Length <= maxLength) return new IssueLink(full, false);
        var url = BuildUrl(title, shortBody);
        if (url.Length <= maxLength) return new IssueLink(url, true);

        // Keep the paste marker; cut the text before it (binary search on characters: escaping changes lengths).
        var marker = ReportBuilder.PasteMarker + "\n";
        var head = shortBody.Replace(marker, "");
        int lo = 0, hi = head.Length;
        while (lo < hi)
        {
            var mid = (lo + hi + 1) / 2;
            if (BuildUrl(title, Cut(head, mid, marker)).Length <= maxLength) lo = mid;
            else hi = mid - 1;
        }
        return new IssueLink(BuildUrl(title, Cut(head, lo, marker)), true);

        static string Cut(string text, int length, string marker)
        {
            if (length > 0 && length < text.Length && char.IsHighSurrogate(text[length - 1])) length--;
            return text[..length] + "…\n\n" + marker;
        }
    }
}
