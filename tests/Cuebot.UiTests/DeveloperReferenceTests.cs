    private static JsonObject Resolve(JsonObject schema, JsonObject schemas) =>
        schema["$ref"] is not null && schemas[RefName(schema)] is JsonObject target ? target : schema;

    private static string RefName(JsonObject schema) => Str(schema, "$ref").Split('/')[^1];

    private static string TypeName(JsonObject schema, JsonObject schemas)
    {
        if (schema["$ref"] is not null) return $"[{RefName(schema)}](#{RefName(schema).ToLowerInvariant()})";
        var type = schema["type"] switch
        {
            JsonArray a => string.Join(" or ", a.Select(t => t!.GetValue<string>())),
            JsonValue v => v.GetValue<string>(),
            _ => schema["oneOf"] is not null || schema["anyOf"] is not null ? "several kinds" : "any",
        };
        if (type == "array" && schema["items"] is JsonObject items) return "list of " + TypeName(items, schemas);
        if (schema["enum"] is JsonArray values) return "one of " + string.Join(", ", values.Select(v => $"`{v}`"));
        return type switch { "string" => "text", "integer" => "whole number", "number" => "number", "boolean" => "true/false", "object" => "object", _ => type };
    }

    private static JsonNode? Sample(JsonObject schema, JsonObject schemas, int depth)
    {
        schema = Resolve(schema, schemas);
        if (schema["enum"] is JsonArray values && values.Count > 0) return values[0]!.DeepClone();
        var type = schema["type"] is JsonValue t ? t.GetValue<string>() : "object";
        switch (type)
        {
            case "string": return "text";
            case "integer": return 1;
            case "number": return 1;
            case "boolean": return true;
            case "array": return depth > 2 || schema["items"] is not JsonObject items ? new JsonArray() : new JsonArray(Sample(items, schemas, depth + 1));
            default:
                var result = new JsonObject();
                if (depth <= 2 && schema["properties"] is JsonObject props)
                    foreach (var (name, prop) in props) result[name] = Sample(prop!.AsObject(), schemas, depth + 1);
                return result;
        }
    }

    private static string Curl(string server, string method, string path, JsonNode? body)
    {
        // Example values that work on that address (a {command} differs per resource).
        var section = path.Split('/', StringSplitOptions.RemoveEmptyEntries)[0];
        var command = section switch
        {
            "giveaway" => "draw", "store" => "approve", "predictions" => "lock", "media" => "skip", _ => "pause",
        };
        var id = section switch
        {
            "commands" => "Hello%20command", "timers" => "Reminder", "media" => "REQUEST_ID", "store" => "REDEMPTION_ID", _ => "Thank%20followers",
        };
        var url = server + path.Replace("{id}", id).Replace("{type}", section == "subactions" ? "chat.send" : "twitch.follow")
            .Replace("{name}", "deaths").Replace("{command}", command);
        var sb = new StringBuilder("curl");
        if (method != "GET") sb.Append($" -X {method}");
        sb.Append(" -H \"Authorization: Bearer YOUR_TOKEN\"");
        if (body is not null)
        {
            var json = body.ToJsonString(new JsonSerializerOptions { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping })
                .Replace("'", "'\\''");
            sb.Append(" -H \"Content-Type: application/json\" \\\n  -d '").Append(json).Append('\'');
        }
        sb.Append(" \\\n  \"").Append(url).Append('"');
        return sb.ToString();
    }

