    [Fact]
    public void Every_CPH_member_has_help_with_an_example()
    {
        var problems = new List<string>();
        foreach (var area in CphAreas())
        {
            var help = CphHelp(area.Key);
            foreach (var name in area.Members.Select(m => m.Name).Distinct())
            {
                if (!help.TryGetValue(name, out var entry)) problems.Add($"cph/{area.Key}.json: no entry for {name}");
                else
                {
                    if (string.IsNullOrWhiteSpace(Str(entry, "description"))) problems.Add($"cph/{area.Key}.json: {name} has no description");
                    if (string.IsNullOrWhiteSpace(Str(entry, "example"))) problems.Add($"cph/{area.Key}.json: {name} has no example");
                }
            }
            var names = area.Members.Select(m => m.Name).ToHashSet(StringComparer.Ordinal);
            problems.AddRange(help.Keys.Where(k => !names.Contains(k)).Select(k => $"cph/{area.Key}.json: {k} is not in CphProxy.{area.File}"));
        }
        var files = Directory.Exists(Path.Combine(HelpDir, "cph")) ? Directory.GetFiles(Path.Combine(HelpDir, "cph"), "*.json") : [];
        var keys = CphAreas().Select(a => a.Key).ToHashSet();
        problems.AddRange(files.Select(Path.GetFileNameWithoutExtension).Where(k => !keys.Contains(k!)).Select(k => $"cph/{k}.json: no such CphProxy file"));
        Assert.True(problems.Count == 0, $"{problems.Count} CPH help problems:\n" + string.Join("\n", problems));
    }

    [Fact]
    public void Every_CPH_example_compiles()
    {
        var examples = CphAreas().SelectMany(a => CphHelp(a.Key).Select(e => (Where: $"cph/{a.Key}.json {e.Key}", Code: Str(e.Value, "example"))))
            .Where(e => e.Code.Length > 0).ToArray();
        using var host = new CphInlineHost();
        if (CompileInline(host, examples.Select(e => e.Code).ToArray()) is null) return;
        var failures = examples.Select(e => CompileInline(host, [e.Code]) is { } error ? $"{e.Where}: {error}" : null).OfType<string>().ToArray();
        Assert.True(failures.Length == 0, $"{failures.Length} C# examples do not compile:\n" + string.Join("\n", failures));
    }

    /// <summary>The C# blocks of the guides compile: CPHInline classes as Streamer.bot code, the rest as Cuebot scripts.</summary>
    [Fact]
    public void Guide_CSharp_examples_compile()
    {
        var failures = new List<string>();
        using var host = new CphInlineHost();
        var compiler = new Cuebot.Scripting.CSharpScriptCompiler();
        foreach (var guide in new[] { "scripting.md", "api.md" })
        {
            var path = Path.Combine(Root, "website", "docs", "guides", guide);
            if (!File.Exists(path)) continue;
            var blocks = System.Text.RegularExpressions.Regex.Matches(File.ReadAllText(path), "```csharp\n(.*?)```", System.Text.RegularExpressions.RegexOptions.Singleline);
            foreach (var code in blocks.Select(b => b.Groups[1].Value))
            {
                try
                {
                    if (CphInlineHost.IsInlineClass(code)) host.Get(code);
                    else compiler.GetRunner(code);
                }
                catch (ScriptException ex)
                {
                    failures.Add($"{guide}: {ex.Message.ReplaceLineEndings(" ")}\n{code}");
                }
            }
        }
        Assert.True(failures.Count == 0, string.Join("\n\n", failures));
    }

    [Fact]
    public void Every_script_function_has_help_for_each_parameter_and_an_example()
    {
        var problems = new List<string>();
        var help = FunctionHelp();
        foreach (var f in Functions)
        {
            if (!help.TryGetValue(f.Name, out var entry)) { problems.Add($"functions: no entry for {f.Name}"); continue; }
            if (string.IsNullOrWhiteSpace(Str(entry, "description"))) problems.Add($"{f.Name}: no description");
            var parameters = entry["parameters"] as JsonObject ?? [];
            foreach (var p in f.ParameterNames.Where(p => string.IsNullOrWhiteSpace(parameters[p]?.GetValue<string>()))) problems.Add($"{f.Name}: parameter '{p}' has no help");
            foreach (var p in parameters.Select(p => p.Key).Where(p => !f.ParameterNames.Contains(p))) problems.Add($"{f.Name}: no parameter '{p}'");
            if (entry["example"] is not JsonObject example) problems.Add($"{f.Name}: no example object");
            else foreach (var p in example.Select(p => p.Key).Where(p => !f.ParameterNames.Contains(p))) problems.Add($"{f.Name}: example uses unknown parameter '{p}'");
        }
        var names = Functions.Select(f => f.Name).ToHashSet(StringComparer.OrdinalIgnoreCase);
        problems.AddRange(help.Keys.Where(k => !names.Contains(k)).Select(k => $"functions: {k} does not exist"));
        Assert.True(problems.Count == 0, $"{problems.Count} script function help problems:\n" + string.Join("\n", problems));
    }

    [Fact]
    public void Developer_reference_pages_are_up_to_date()
    {
        var root = Path.Combine(Root, "website", "docs", "reference");
        var pages = BuildPages();
        if (Environment.GetEnvironmentVariable("CUEBOT_WRITE_REFERENCE") is { Length: > 0 })
        {
            foreach (var dir in OwnDirs.Select(d => Path.Combine(root, d)).Where(Directory.Exists)) Directory.Delete(dir, recursive: true);
            foreach (var (file, text) in pages)
            {
                var path = Path.Combine(root, file);
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                File.WriteAllText(path, text);
            }
        }
        static string Lf(string text) => text.Replace("\r\n", "\n");
        var stale = pages.Where(p => !File.Exists(Path.Combine(root, p.Key)) || Lf(File.ReadAllText(Path.Combine(root, p.Key))) != p.Value)
            .Select(p => p.Key).ToArray();
        var extra = OwnDirs.Select(d => Path.Combine(root, d)).Where(Directory.Exists)
            .SelectMany(d => Directory.EnumerateFiles(d, "*.md", SearchOption.AllDirectories))
            .Select(f => Path.GetRelativePath(root, f).Replace('\\', '/')).Where(f => !pages.ContainsKey(f)).ToArray();
        Assert.True(stale.Length == 0 && extra.Length == 0,
            "Developer reference pages are out of date; run the tests with CUEBOT_WRITE_REFERENCE=1 to rewrite them.\n" +
            string.Join("\n", stale.Select(s => "stale: " + s).Concat(extra.Select(e => "extra: " + e))));
    }

