    private static IReadOnlyList<CphArea> ReadCphAreas()
    {
        var dir = Path.Combine(Root, "src", "Cuebot.Scripting", "CSharp", "Compat");
        var known = AreaTitles.Select(a => a.File).ToHashSet();
        var unknown = Directory.GetFiles(dir, "CphProxy*.cs").Select(f => Path.GetFileNameWithoutExtension(f)["CphProxy".Length..].TrimStart('.'))
            .Where(f => !known.Contains(f)).ToArray();
        Assert.True(unknown.Length == 0, "Add a title for CphProxy." + string.Join(", CphProxy.", unknown) + " to DeveloperReferenceTests.AreaTitles");
        return AreaTitles.Select(a =>
        {
            var file = Path.Combine(dir, a.File.Length == 0 ? "CphProxy.cs" : $"CphProxy.{a.File}.cs");
            var root = CSharpSyntaxTree.ParseText(File.ReadAllText(file)).GetCompilationUnitRoot();
            var members = root.DescendantNodes().OfType<ClassDeclarationSyntax>().Where(c => c.Identifier.Text == "CphProxy")
                .SelectMany(c => c.Members).Where(m => m.Modifiers.Any(SyntaxKind.PublicKeyword))
                .Select(m => m switch
                {
                    MethodDeclarationSyntax x => new CphMember(x.Identifier.Text,
                        $"{x.ReturnType} {x.Identifier}{x.TypeParameterList}{Flat(x.ParameterList.ToString())}"),
                    PropertyDeclarationSyntax p => new CphMember(p.Identifier.Text, $"{p.Type} {p.Identifier} {{ get; }}"),
                    _ => null,
                }).OfType<CphMember>().ToArray();
            return new CphArea(a.File.Length == 0 ? "core" : a.File.ToLowerInvariant(), a.File.Length == 0 ? "cs" : a.File + ".cs", a.Title, members);
        }).ToArray();
    }

    private static string Flat(string text) => string.Join(" ", text.Split((char[])['\r', '\n'], StringSplitOptions.RemoveEmptyEntries).Select(l => l.Trim())).Replace("( ", "(");

    private static Dictionary<string, JsonObject> CphHelp(string key)
    {
        var path = Path.Combine(HelpDir, "cph", key + ".json");
        if (!File.Exists(path)) return [];
        var members = JsonNode.Parse(File.ReadAllText(path))?["members"] as JsonObject ?? [];
        return members.ToDictionary(m => m.Key, m => m.Value!.AsObject(), StringComparer.Ordinal);
    }

    /// <summary>Compiles the examples as method bodies of one CPHInline class; null when they compile, else the error.</summary>
    private static string? CompileInline(CphInlineHost host, IReadOnlyList<string> examples)
    {
        var code = "public class CPHInline\n{\n    public bool Execute() => true;\n"
                   + string.Concat(examples.Select((c, i) => $"    public void M{i}()\n    {{\n{c}\n    }}\n")) + "}\n";
        try
        {
            host.Get(code);
            return null;
        }
        catch (ScriptException ex)
        {
            return ex.Message.ReplaceLineEndings(" ");
        }
    }

