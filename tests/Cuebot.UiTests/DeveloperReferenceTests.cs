        index.Append("In a **Run C# code** step you can use `CPH`, a toolbox of ready-made methods. `CPH.SendMessage(\"Hi!\")` sends a chat " +
                     "message, `CPH.ObsSetScene(\"Gameplay\")` switches your OBS scene, and so on. The names are the same as in " +
                     "Streamer.bot, so code written for Streamer.bot works in Cuebot.\n\n");
        index.Append("New to code? Read [Writing code (C# and Python)](../../guides/scripting.md) first. It shows where the code goes " +
                     "and how a whole script looks. Every example on these pages goes inside `Execute()`:\n\n");
        index.Append("```csharp\npublic class CPHInline\n{\n    public bool Execute()\n    {\n        // the example goes here\n        return true;\n    }\n}\n```\n\n");
        index.Append("| Area | Methods |\n| --- | --- |\n");
        foreach (var a in areas) index.Append($"| [{a.Title}]({a.Key}.md) | {a.Members.Select(m => m.Name).Distinct().Count()} |\n");
        index.Append("\nPython code has no `CPH`. It uses [script functions](../script-functions/index.md) instead, which C# can use too.\n");
        pages["csharp/index.md"] = index.ToString();

        foreach (var a in areas)
        {
            var help = CphHelp(a.Key);
            var sb = new StringBuilder(Generated);
            sb.Append($"# {a.Title}\n\nC# methods for a **Run C# code** step. See [C# methods](index.md) for how to use them.\n");
            foreach (var group in a.Members.GroupBy(m => m.Name))
            {
                var entry = help.GetValueOrDefault(group.Key);
                sb.Append($"\n## {group.Key}\n\n");
                if (Str(entry, "description") is { Length: > 0 } d) sb.Append(d).Append("\n\n");
                sb.Append("```csharp\n");
                foreach (var m in group) sb.Append(m.Signature).Append('\n');
                sb.Append("```\n\n");
                if (Str(entry, "returns") is { Length: > 0 } r) sb.Append($"**Gives back:** {r}\n\n");
                if (Str(entry, "example") is { Length: > 0 } e) sb.Append("**Example**\n\n```csharp\n").Append(e.TrimEnd()).Append("\n```\n");
            }
            pages[$"csharp/{a.Key}.md"] = sb.ToString();
        }
    }

    private void FunctionPages(SortedDictionary<string, string> pages)
    {
        var help = FunctionHelp();
        var groups = Functions.GroupBy(f => Prefix(f.Name), StringComparer.OrdinalIgnoreCase).OrderBy(g => g.Key, StringComparer.OrdinalIgnoreCase).ToArray();
        var index = new StringBuilder(Generated);
        index.Append("# Script functions\n\n");
        index.Append("Script functions are Cuebot's own tools for code. **C# and Python can both use them.** Each one has a name, " +
                     "like `speech.speak`, and takes named values, like `text`.\n\n");
        index.Append("```csharp\n// C#: await the call; the answer is JSON\nvar answer = await Cb.Call(\"speech.speak\", new { text = \"Hello!\" });\n```\n\n");
        index.Append("```python\n# Python: no await needed\nanswer = cb.call(\"speech.speak\", text=\"Hello!\")\n```\n\n");
        index.Append("In C#, `Cb.Call` works in plain C# code. Inside a Streamer.bot-style `CPHInline` class, use the [`CPH` methods](../csharp/index.md) instead. " +
                     "See [Writing code (C# and Python)](../../guides/scripting.md) for whole examples.\n\n");
        index.Append("| Area | Functions |\n| --- | --- |\n");
        foreach (var g in groups) index.Append($"| [{AreaTitle(g.Key)}]({g.Key.ToLowerInvariant()}.md) | {g.Count()} |\n");
        pages["script-functions/index.md"] = index.ToString();

        foreach (var g in groups)
        {
            var sb = new StringBuilder(Generated);
            sb.Append($"# {AreaTitle(g.Key)} script functions\n\nFunctions for C# (`Cb.Call`) and Python (`cb.call`). See [Script functions](index.md) for how to use them.\n");
            foreach (var f in g.OrderBy(f => f.Name, StringComparer.OrdinalIgnoreCase))
            {
                var entry = help.GetValueOrDefault(f.Name);
                sb.Append($"\n## {f.Name}\n\n");
                sb.Append((Str(entry, "description") is { Length: > 0 } d ? d : f.Description)).Append("\n\n");
                if (f.ParameterNames.Count > 0)
                {
                    var parameters = entry?["parameters"] as JsonObject;
                    sb.Append("| Value | What to put in |\n| --- | --- |\n");
                    foreach (var p in f.ParameterNames) sb.Append($"| `{p}` | {Cell(parameters?[p]?.GetValue<string>() ?? "")} |\n");
                    sb.Append('\n');
                }
                if (Str(entry, "returns") is { Length: > 0 } r) sb.Append($"**Gives back:** {r}\n\n");
                var example = entry?["example"] as JsonObject ?? [];
                sb.Append("=== \"C#\"\n\n    ```csharp\n    ").Append(CSharpCall(f.Name, example).Replace("\n", "\n    ")).Append("\n    ```\n\n");
                sb.Append("=== \"Python\"\n\n    ```python\n    ").Append(PythonCall(f.Name, example).Replace("\n", "\n    ")).Append("\n    ```\n");
            }
            pages[$"script-functions/{g.Key.ToLowerInvariant()}.md"] = sb.ToString();
        }
    }

    private const string ApiServerUrl = "http://127.0.0.1:7475/api/v1";

    private static JsonObject RestHelp() =>
        JsonNode.Parse(File.ReadAllText(Path.Combine(Root, "src", "Cuebot.Server", "Api", "Help", "rest.json")))!.AsObject();

    private sealed record RestOperation(string Tag, string Method, string Path, JsonObject Op, JsonObject[] Parameters, JsonObject? Body)
    {
        public string Key => $"{Method} {Path}";
    }

    private static IReadOnlyList<RestOperation> RestOperations(JsonObject doc)
    {
        var ops = new List<RestOperation>();
        foreach (var (path, item) in doc["paths"]!.AsObject())
        {
            var shared = item!["parameters"] as JsonArray ?? [];
            foreach (var (method, op) in item.AsObject().Where(p => p.Key != "parameters"))
                ops.Add(new RestOperation((op!["tags"] as JsonArray)?[0]?.GetValue<string>() ?? "Other", method.ToUpperInvariant(), path, op.AsObject(),
                    shared.Concat(op["parameters"] as JsonArray ?? []).OfType<JsonObject>().ToArray(),
                    op["requestBody"]?["content"]?["application/json"]?["schema"] as JsonObject));
        }
        return ops;
    }

    /// <summary>Every field the page lists: (help key, schema), body fields as "METHOD /path.field", shapes as "Schema.field".</summary>
    private static IEnumerable<(string Key, JsonObject Schema)> RestFields(JsonObject doc)
    {
        var schemas = doc["components"]?["schemas"] as JsonObject ?? [];
        foreach (var op in RestOperations(doc).Where(o => o.Body is { } b && b["$ref"] is null))
            foreach (var (name, prop) in Resolve(op.Body!, schemas)["properties"] as JsonObject ?? [])
                yield return ($"{op.Key}.{name}", prop!.AsObject());
        foreach (var (schema, value) in schemas)
            foreach (var (name, prop) in value!["properties"] as JsonObject ?? [])
                yield return ($"{schema}.{name}", prop!.AsObject());
    }

    [Fact]
    public void Every_REST_operation_and_field_has_plain_help()
    {
        var doc = OpenApiDocument.Build(ApiServerUrl, "0");
        var schemas = doc["components"]?["schemas"] as JsonObject ?? [];
        var help = RestHelp();
        var operations = help["operations"] as JsonObject ?? [];
        var fields = help["fields"] as JsonObject ?? [];
        var problems = new List<string>();
        var ops = RestOperations(doc);
        foreach (var op in ops)
        {
            var entry = operations[op.Key] as JsonObject;
            if (string.IsNullOrWhiteSpace(Str(entry, "description"))) problems.Add($"{op.Key}: no description");
            if (op.Body is not null && entry?["example"] is null) problems.Add($"{op.Key}: has a body but no example");
        }
        var keys = ops.Select(o => o.Key).ToHashSet();
        problems.AddRange(operations.Select(o => o.Key).Where(k => !keys.Contains(k)).Select(k => $"operations: no such operation {k}"));
        var all = RestFields(doc).ToArray();
        foreach (var (key, schema) in all.Where(f => Str(Resolve(f.Schema, schemas), "description").Length == 0 && Str(fields, f.Key).Length == 0))
            problems.Add($"{key}: no description");
        var fieldKeys = all.Select(f => f.Key).ToHashSet();
        problems.AddRange(fields.Select(f => f.Key).Where(k => !fieldKeys.Contains(k)).Select(k => $"fields: no such field {k}"));
        Assert.True(problems.Count == 0, $"{problems.Count} REST help problems:\n" + string.Join("\n", problems));
    }

    /// <summary>The OpenAPI shapes of actions, commands and timers list every field the API really sends and accepts.</summary>
    [Fact]
    public void REST_schemas_list_every_field_of_the_saved_models()
    {
        var schemas = OpenApiDocument.Build(ApiServerUrl, "0")["components"]!["schemas"]!.AsObject();
        var problems = new List<string>();
        void Check(string schema, object model)
        {
            var props = schemas[schema]?["properties"] as JsonObject ?? [];
            foreach (var key in ApiOperations.ToObject(model).Select(p => p.Key).Where(k => !props.ContainsKey(k))) problems.Add($"{schema}.{key}");
        }
        Check("Action", new Cuebot.Core.Actions.ActionDefinition());
        Check("Trigger", new Cuebot.Core.Actions.TriggerDefinition());
        Check("SubAction", new Cuebot.Core.Actions.SubActionDefinition());
        Check("Timer", new Cuebot.Core.Actions.TimerDefinition());
        Check("Command", new Cuebot.Core.Commands.CommandDefinition());
        Assert.True(problems.Count == 0, "Fields missing from OpenApiDocument: " + string.Join(", ", problems));
    }

    private static string RestApiPage()
    {
        const string server = ApiServerUrl;
        var doc = OpenApiDocument.Build(server, "0");
        var schemas = doc["components"]?["schemas"] as JsonObject ?? [];
        var help = RestHelp();
        var opHelp = help["operations"] as JsonObject ?? [];
        var fieldHelp = help["fields"] as JsonObject ?? [];
        string FieldText(string key, JsonObject prop) => Str(fieldHelp, key) is { Length: > 0 } h ? h : Str(Resolve(prop, schemas), "description");
        var sb = new StringBuilder(Generated);
        sb.Append("# REST API reference\n\n");
        sb.Append("Every web address of Cuebot's **REST API**, made from the same description Cuebot serves at `/api/v1/openapi.json`. " +
                  "New to this? Read [Controlling Cuebot from other programs](../guides/api.md) first: it shows how to turn the API on, " +
                  "where the token is, and how to try it.\n\n");
        sb.Append("- **Address:** `http://127.0.0.1:7475/api/v1` (the port is on the REST API card on **Apps > Servers**).\n");
        sb.Append("- **Token:** every request needs the header `Authorization: Bearer YOUR_TOKEN`. Without it you get `401`.\n");
        sb.Append("- **Data:** requests and answers are JSON. Errors look like `{\"error\": \"...\", \"details\": [{\"path\": \"...\", \"message\": \"...\"}]}`.\n");
        sb.Append("- **`{id}`** in an address can be the id or the name of the action, command or timer. Put `%20` for a space.\n\n");
        sb.Append("The examples use `curl`, a small program that comes with Windows 10 and 11, macOS and Linux. Put your token in place of `YOUR_TOKEN`.\n");

        foreach (var tag in RestOperations(doc).GroupBy(o => o.Tag))
        {
            sb.Append($"\n## {tag.Key}\n");
            foreach (var op in tag)
            {
                var entry = opHelp[op.Key] as JsonObject;
                sb.Append($"\n### {op.Method} {op.Path}\n\n");
                var text = Str(entry, "description") is { Length: > 0 } d ? d : Str(op.Op, "summary").TrimEnd('.') + ".";
                sb.Append(text).Append("\n\n");
                if (op.Parameters.Length > 0)
                {
                    sb.Append("| In the address | What it is |\n| --- | --- |\n");
                    foreach (var p in op.Parameters)
                        sb.Append($"| `{Str(p, "name")}` ({(Str(p, "in") == "path" ? "required, in the path" : "optional, after ?")}) | {Cell(Str(p, "description"))} |\n");
                    sb.Append('\n');
                }
                if (op.Body is { } body)
                {
                    var resolved = Resolve(body, schemas);
                    if (body["$ref"] is not null) sb.Append($"The body is one [{RefName(body)}](#{RefName(body).ToLowerInvariant()}).\n\n");
                    else if (resolved["properties"] is JsonObject props && props.Count > 0)
                    {
                        sb.Append("| Body field | Type | What it is |\n| --- | --- | --- |\n");
                        foreach (var (name, prop) in props) sb.Append($"| `{name}` | {TypeName(prop!.AsObject(), schemas)} | {Cell(FieldText($"{op.Key}.{name}", prop.AsObject()))} |\n");
                        sb.Append('\n');
                    }
                }
                if (op.Op["responses"] is JsonObject responses)
                    sb.Append("**Answers:** ").Append(string.Join("; ", responses.Select(r => $"`{r.Key}` {Str(r.Value as JsonObject, "description")}"))).Append(".\n\n");
                var example = op.Body is null ? null : entry?["example"]?.DeepClone() ?? Sample(Resolve(op.Body, schemas), schemas, 0);
                sb.Append("```bash\n").Append(Curl(server, op.Method, op.Path, example)).Append("\n```\n");
            }
        }

        sb.Append("\n## Data shapes\n\nThe objects the answers above name, with their fields.\n");
        foreach (var (name, schema) in schemas)
        {
            sb.Append($"\n### {name}\n\n");
            var s = schema!.AsObject();
            if (Str(s, "description") is { Length: > 0 } d) sb.Append(d).Append("\n\n");
            if (s["properties"] is JsonObject props && props.Count > 0)
            {
                sb.Append("| Field | Type | What it is |\n| --- | --- | --- |\n");
                foreach (var (field, prop) in props) sb.Append($"| `{field}` | {TypeName(prop!.AsObject(), schemas)} | {Cell(FieldText($"{name}.{field}", prop.AsObject()))} |\n");
            }
            else sb.Append($"Type: {TypeName(s, schemas)}.\n");
        }
        return sb.ToString();
    }

