    private static string CSharpValue(JsonNode? node) => node switch
    {
        null => "null",
        JsonObject o when o.All(p => SyntaxFacts.IsValidIdentifier(p.Key) && SyntaxFacts.GetKeywordKind(p.Key) == SyntaxKind.None) =>
            "new { " + string.Join(", ", o.Select(p => $"{p.Key} = {CSharpValue(p.Value)}")) + " }",
        JsonObject o => "new Dictionary<string, object?> { " + string.Join(", ", o.Select(p => $"[{Quote(p.Key)}] = {CSharpValue(p.Value)}")) + " }",
        JsonArray a when a.Count > 0 && a.All(i => i is JsonValue v && v.GetValueKind() == JsonValueKind.String) => "new[] { " + string.Join(", ", a.Select(CSharpValue)) + " }",
        JsonArray a => "new object?[] { " + string.Join(", ", a.Select(CSharpValue)) + " }",
        JsonValue v => v.GetValueKind() switch
        {
            JsonValueKind.String => Quote(v.GetValue<string>()),
            JsonValueKind.True => "true",
            JsonValueKind.False => "false",
            _ => v.ToJsonString(),
        },
        _ => node.ToJsonString(),
    };

